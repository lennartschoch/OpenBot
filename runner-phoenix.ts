import { Socket } from "/home/agent/workspace/OpenBot/node_modules/.bun/phoenix@1.8.15/node_modules/phoenix/priv/static/phoenix.mjs";
const socket = new Socket("ws://localhost:3101/api/intelligence-gateway/runner", { authToken: "local-intelligence" });
socket.connect();
await new Promise((r, j) => { socket.onOpen(() => r(0)); socket.onError((e) => j(new Error("ws error " + JSON.stringify(e)))); setTimeout(() => j(new Error("open timeout")), 4000); });
console.log("runner socket open");
const chan = socket.channel("ingestion:ph-1", { thread_id: "ph-1", run_id: "ph-1" });
const push = chan.join();
push.receive("ok", (r: any) => console.log("ingestion join ok:", JSON.stringify(r).slice(0, 120)));
push.receive("error", (e: any) => console.log("ingestion join error:", JSON.stringify(e).slice(0, 200)));
push.receive("timeout", () => console.log("ingestion join TIMEOUT"));
await new Promise((r) => setTimeout(r, 3000));
socket.disconnect();
process.exit(0);
